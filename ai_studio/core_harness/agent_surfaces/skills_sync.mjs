// Both hosts receive the canonical instructions inline, so invoking a skill costs no
// extra read; supporting resources stay in .codex/skills and links are rebased there.
//
//   node ai_studio/core_harness/agent_surfaces/skills_sync.mjs
//
// The ownership marker prevents overwriting hand-written host skills.

import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync, statSync, rmSync } from "node:fs";
import { join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);

function usage() {
  console.error(`usage:
  node ai_studio/core_harness/agent_surfaces/skills_sync.mjs [--check] [--root <dir>]

Generate .agents/skills/* and .claude/skills/* pointers from .codex/skills/*.
--check reports drift without writing.`);
  process.exit(2);
}

function takeString(name, fallback) {
  const index = args.indexOf(name);
  if (index === -1) return fallback;
  const value = args[index + 1];
  if (!value || value.startsWith("--")) usage();
  args.splice(index, 2);
  return value;
}

const check = args.includes("--check");
if (check) args.splice(args.indexOf("--check"), 1);
if (args.includes("--help") || args.includes("-h")) usage();

const root = resolve(takeString("--root", fileURLToPath(new URL("../../..", import.meta.url))));
if (args.length > 0) usage();

const srcDir = join(root, ".codex", "skills");
const MARKER = "<!-- generated by ai_studio/core_harness/agent_surfaces/skills_sync.mjs; edit .codex/skills instead -->";

function parseFrontmatter(text) {
  text = text.replace(/^\uFEFF/, "");
  const lines = text.split(/\r?\n/);
  if (lines[0] !== "---") return {};
  const end = lines.indexOf("---", 1);
  if (end === -1) return {};
  const fields = {};
  let current = null;
  for (const line of lines.slice(1, end)) {
    const m = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (m) {
      current = m[1];
      fields[current] = m[2].trim();
    } else if (current && /^\s+/.test(line)) {
      fields[current] += " " + line.trim();
    }
  }
  for (const k of Object.keys(fields)) {
    fields[k] = fields[k].replace(/^["']|["']$/g, "");
  }
  return fields;
}

// Generated surfaces sit at the same depth as .codex/skills, so links that already
// climb to the repo root stay valid; only links into the skill folder are rebased.
function inlineCanonicalBody(text, name) {
  const body = text.replace(/^﻿/, "").replace(/\r\n/g, "\n").replace(/^---\n[\s\S]*?\n---\n/, "");
  return body.replace(/\]\(([^)\s]+)\)/g, (match, target) => {
    if (/^(?:[a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return match;
    const hash = target.indexOf("#");
    const path = hash < 0 ? target : target.slice(0, hash);
    const fragment = hash < 0 ? "" : target.slice(hash);
    const canonical = posix.normalize(posix.join(".codex/skills", name, path));
    return `](${posix.relative(posix.join(".claude/skills", name), canonical)}${fragment})`;
  });
}

function allowsImplicitInvocation(yaml) {
  const lines = (yaml || "").split(/\r?\n/);
  const inline = lines.find((line) => /^policy:\s*\{/.test(line));
  if (inline) {
    const match = inline.match(/^policy:\s*\{\s*allow_implicit_invocation:\s*(true|false)\s*\}\s*(?:#.*)?$/);
    if (!match) throw new Error("invocation policy requires a YAML boolean in a supported block or one-key inline mapping");
    return match[1] === "true";
  }
  const start = lines.findIndex((line) => /^policy:\s*(?:#.*)?$/.test(line));
  if (start < 0) {
    if (/allow_implicit_invocation/.test(yaml || "")) throw new Error("invocation policy requires a YAML boolean mapping");
    return true;
  }
  for (const line of lines.slice(start + 1)) {
    if (/^[^\s#]/.test(line)) break;
    const match = line.match(/^\s+allow_implicit_invocation:\s*(true|false)\s*(?:#.*)?$/);
    if (match) return match[1] === "true";
    if (/^\s+allow_implicit_invocation:/.test(line)) {
      throw new Error("allow_implicit_invocation must be a YAML boolean");
    }
  }
  if (/allow_implicit_invocation/.test(yaml || "")) throw new Error("invocation policy requires a YAML boolean mapping");
  return true;
}

if (!existsSync(srcDir)) {
  console.error(`error: ${srcDir} not found`);
  process.exit(1);
}

const skills = [];
const invalid = [];
for (const name of readdirSync(srcDir)) {
  const skillDir = join(srcDir, name);
  const skillFile = join(skillDir, "SKILL.md");
  if (!statSync(skillDir).isDirectory() || !existsSync(skillFile)) continue;
  const fields = parseFrontmatter(readFileSync(skillFile, "utf8"));
  if (fields.name !== name || name.length > 64 || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
    invalid.push(`${name}: name must match its lowercase hyphenated directory`);
  }
  if (!fields.description?.trim() || fields.description.length > 1024) {
    invalid.push(`${name}: description must contain 1-1024 characters`);
  }
  const metadataPath = join(skillDir, "agents", "openai.yaml");
  const metadata = existsSync(metadataPath) ? readFileSync(metadataPath, "utf8") : null;
  let implicit = true;
  try {
    implicit = allowsImplicitInvocation(metadata);
  } catch (error) {
    invalid.push(`${name}: ${error.message}`);
  }
  skills.push({ name, fields, metadata, implicit, canonical: readFileSync(skillFile, "utf8") });
}
if (invalid.length) {
  console.error(invalid.join("\n"));
  process.exit(1);
}

let failed = false;
for (const surface of [".agents", ".claude"]) {
const dstDir = join(root, surface, "skills");
let written = 0;
let removed = 0;
let skipped = 0;
const drift = [];
const seen = new Set();
for (const { name, fields, metadata, implicit, canonical } of skills) {
  seen.add(name);

  const outDir = join(dstDir, name);
  const outFile = join(outDir, "SKILL.md");
  if (existsSync(outFile) && !readFileSync(outFile, "utf8").includes(MARKER)) {
    console.error(`skill collision: ${surface}/skills/${name} is hand-written; canonical discovery is blocked`);
    failed = true;
    skipped++;
    continue;
  }

  const body = [
    "---",
    `name: ${fields.name}`,
    `description: ${JSON.stringify(fields.description)}`,
    ...(surface === ".claude" && !implicit ? ["disable-model-invocation: true"] : []),
    "---",
    MARKER,
    `<!-- skill folder: .codex/skills/${name}/ -- resolve plain references/, scripts/ and agents/ paths below against it -->`,
    inlineCanonicalBody(canonical, name).replace(/^\n+/, ""),
  ].join("\n");

  const metadataOut = join(outDir, "agents", "openai.yaml");
  if (check) {
    const existing = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;
    if (existing !== body) drift.push(name);
    if (surface === ".agents") {
      const existingMetadata = existsSync(metadataOut) ? readFileSync(metadataOut, "utf8") : null;
      if (existingMetadata !== metadata) drift.push(`${name}/agents/openai.yaml`);
    }
    continue;
  }

  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, body);
  if (surface === ".agents") {
    if (metadata !== null) {
      mkdirSync(join(outDir, "agents"), { recursive: true });
      writeFileSync(metadataOut, metadata);
    } else if (existsSync(metadataOut)) {
      rmSync(metadataOut);
    }
  }
  console.log(`generated: ${name}`);
  written++;
}

if (existsSync(dstDir)) {
  for (const name of readdirSync(dstDir)) {
    if (seen.has(name)) continue;
    const outDir = join(dstDir, name);
    const outFile = join(outDir, "SKILL.md");
    if (!statSync(outDir).isDirectory() || !existsSync(outFile)) continue;
    const text = readFileSync(outFile, "utf8");
    if (!text.includes(MARKER)) {
      skipped++;
      continue;
    }
    if (check) {
      drift.push(name);
      continue;
    }
    rmSync(outDir, { recursive: true, force: true });
    console.log(`removed stale generated pointer: ${name}`);
    removed++;
  }
}

if (check) {
  if (drift.length) {
    console.error(`skills drift: ${drift.length} ${surface}/skills pointer(s) out of sync with .codex/skills: ${drift.join(", ")}`);
    console.error("fix: run `node ai_studio/core_harness/agent_surfaces/skills_sync.mjs`");
    failed = true;
    continue;
  }
  console.log(`skills in sync: ${surface}/skills matches .codex/skills`);
  continue;
}
console.log(`${surface}/skills done: ${written} generated, ${removed} stale removed, ${skipped} skipped`);
}
process.exitCode = failed ? 1 : 0;
